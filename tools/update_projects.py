"""Build the project pool catalogue (projects/projects.yml) from GitHub.

Reads the public repository Erasmus-CTM/thematicProjects: every folder
<Subject>/<Topic>/<Project>/ with a README.md is one project. The README holds
the metadata as a bullet list:

    # Road planning

    * **Workload:** 4-6 hours
    * **Study programme:** Civil engineering; Land surveying
    * **Prerequisites:** Planar curves; curvature
    * **Languages:** Danish

Optional (proposed, not yet used in the repository):

    * **University:** AAU
    * **Authors:** Jane Doe; John Doe

Projects from other sources (e.g. the DTU site) are listed by hand in
projects/projects-extra.yml and are appended unchanged.

Run from the folder ctm-website/ (standard library + git):

    python -I tools/update_projects.py

Then render as usual (quarto preview / quarto render). Rendering itself never
touches the network - the catalogue is the checked-in projects.yml.
"""
import json
import pathlib
import re
import subprocess
import sys
import tempfile
import urllib.parse

ORG = "Erasmus-CTM"
REPO = "thematicProjects"
BRANCH = "main"
# Without a "University:" line in the README this value is used. Source: the
# partners' overview table (WP5 A3): "39 projects from AAU".
DEFAULT_UNIVERSITY = "AAU"

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "projects" / "projects.yml"
EXTRA = ROOT / "projects" / "projects-extra.yml"

SUBJECTS = {"Calculus": "Calculus", "LinearAlgebra": "Linear Algebra"}
LANG_CODES = {"DA": "Danish", "EN": "English", "DE": "German", "NO": "Norwegian", "SV": "Swedish"}


def split_camel(name: str) -> str:
    """'ComplexNumbers' -> 'Complex Numbers', 'PcaWindTurbines' -> 'Pca Wind Turbines'."""
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name)


def q(value: str) -> str:
    """YAML scalar: a JSON string is a valid double-quoted YAML string."""
    return json.dumps(value, ensure_ascii=False)


def parse_readme(text: str) -> dict:
    meta = {}
    m = re.search(r"^#\s+(.+)$", text, re.M)
    if m:
        meta["title"] = m.group(1).strip()
    for key, value in re.findall(r"^\s*[*-]\s*\*\*([^*:]+):?\*\*:?\s*(.+)$", text, re.M):
        meta[key.strip().lower()] = value.strip()
    return meta


def main() -> int:
    # Shallow clone WITHOUT checkout into a temporary folder; files are read straight
    # from git. (No GitHub API -> no rate limit. No checkout -> works on Windows,
    # where the repository's folder "aux/" is a reserved name and cannot be created.)
    with tempfile.TemporaryDirectory() as tmp:
        repo = pathlib.Path(tmp) / REPO
        subprocess.run(["git", "clone", "--quiet", "--depth", "1", "--no-checkout",
                        "--branch", BRANCH, f"https://github.com/{ORG}/{REPO}.git", str(repo)],
                       check=True)
        return build(repo)


def git(repo: pathlib.Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True,
                          capture_output=True).stdout.decode("utf-8")


def build(repo: pathlib.Path) -> int:
    paths = sorted(git(repo, "-c", "core.quotePath=false", "ls-tree", "-r",
                       "--name-only", "HEAD").splitlines())
    readmes = [p for p in paths if p.count("/") == 3 and p.endswith("/README.md")]

    items = []
    for readme in readmes:
        folder = readme.rsplit("/", 1)[0]
        subject, topic, project = folder.split("/")
        meta = parse_readme(git(repo, "show", f"HEAD:{readme}"))

        # language versions actually present as rendered HTML files (…DA.html, …EN.html)
        versions = sorted({m.group(1) for p in paths if p.startswith(folder + "/")
                           for m in [re.search(r"([A-Z]{2})\.html$", p)] if m})
        languages = meta.get("languages") or ", ".join(LANG_CODES.get(v, v) for v in versions)

        items.append({
            "title": meta.get("title", split_camel(project)),
            "path": f"https://github.com/{ORG}/{REPO}/tree/{BRANCH}/{urllib.parse.quote(folder)}",
            "subject": SUBJECTS.get(subject, split_camel(subject)),
            "topic": split_camel(topic),
            "workload": meta.get("workload", ""),
            "programme": meta.get("study programme", ""),
            "prerequisites": meta.get("prerequisites", ""),
            "languages": languages.replace(";", ","),
            "university": meta.get("university", DEFAULT_UNIVERSITY),
            "authors": meta.get("authors", ""),
            "source": f"{REPO}",
            "categories": [SUBJECTS.get(subject, subject), split_camel(topic)],
        })

    lines = [
        "# GENERATED by tools/update_projects.py from github.com/Erasmus-CTM/thematicProjects.",
        "# Do not edit by hand - change the README.md in thematicProjects instead,",
        "# or add projects from other sources to projects-extra.yml.",
    ]
    for it in items:
        lines.append(f"- title: {q(it['title'])}")
        for k in ("path", "subject", "topic", "workload", "programme", "prerequisites",
                  "languages", "university", "authors", "source"):
            lines.append(f"  {k}: {q(it[k])}")
        lines.append("  categories: [" + ", ".join(q(c) for c in it["categories"]) + "]")
    if EXTRA.exists():
        lines.append("")
        lines.append("# ---- appended from projects-extra.yml ----")
        lines.extend(l for l in EXTRA.read_text(encoding="utf-8").splitlines()
                     if not l.lstrip().startswith("#"))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(items)} projects from {REPO} (+ extra) -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
